public class MultiCalc
{
    public int Somar(int aValue1, int aValue2)
    {
        return aValue1 + aValue2;
    }

    public int Somar(int aValue1, int aValue2, int aValue3)
    {
        return aValue1 + aValue2 + aValue3;
    }

    public double Somar(double aValue1, double aValue2)
    {
        return aValue1 + aValue2;
    }
}